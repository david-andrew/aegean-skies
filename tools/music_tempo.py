#!/usr/bin/env python3
"""The score's quarter note through each catalogue piece, for showing a played note's written
value (src/note_value.jo): src/music_tempo.jo, generated from data/music/source/<source>.mid (its
tempo map) and data/music/performance.json (how much longer or shorter the performance is than the
score). A small reader of standard MIDI files; a piece with its own tempo map also needs
tools/music_performance.py (mido).

  python3 tools/music_tempo.py            (writes src/music_tempo.jo)
"""
import json, re, struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _varlen(b, i):
    v = 0
    while True:
        c = b[i]; i += 1
        v = (v << 7) | (c & 0x7F)
        if not c & 0x80:
            return v, i


def read_tempo_map(path):
    """(ticks per quarter, [(tick, microseconds per quarter)], the last tick a note sounds to)."""
    b = Path(path).read_bytes()
    if b[:4] != b'MThd':
        raise ValueError(f'{path}: not a MIDI file')
    hlen = struct.unpack('>I', b[4:8])[0]
    _fmt, ntrks, division = struct.unpack('>HHH', b[8:14])
    if division & 0x8000:
        raise ValueError(f'{path}: SMPTE time is not handled')
    i = 8 + hlen
    tempos = {0: 500000}
    end = 0
    for _ in range(ntrks):
        assert b[i:i + 4] == b'MTrk', path
        n = struct.unpack('>I', b[i + 4:i + 8])[0]
        j = i + 8; stop = j + n; tick = 0; status = 0
        while j < stop:
            dt, j = _varlen(b, j); tick += dt
            c = b[j]
            if c == 0xFF:
                kind = b[j + 1]; ln, j = _varlen(b, j + 2)
                if kind == 0x51 and ln == 3:
                    tempos[tick] = (b[j] << 16) | (b[j + 1] << 8) | b[j + 2]
                j += ln
            elif c in (0xF0, 0xF7):
                ln, j = _varlen(b, j + 1); j += ln
            else:
                if c & 0x80:
                    status = c; j += 1
                hi = status & 0xF0
                j += 1 if hi in (0xC0, 0xD0) else 2
                if hi in (0x80, 0x90):
                    end = max(end, tick)
        i = stop
    return division, sorted(tempos.items()), end


def quarter_map(path, stretch):
    """[(second as played, quarter seconds)]: the tempo map in played time, near-equal steps merged."""
    ppq, tempos, end = read_tempo_map(path)
    out = []
    at = 0.0
    for k, (tick, us) in enumerate(tempos):
        if tick > end:
            break
        q = us / 1e6 * stretch
        if not out or abs(q - out[-1][1]) / out[-1][1] > 0.03:
            out.append((round(at * stretch, 3), round(q, 4)))
        nxt = tempos[k + 1][0] if k + 1 < len(tempos) else end
        at += (min(nxt, end) - tick) / ppq * us / 1e6
    return out


def played_quarter_map(name, stretch):
    """A piece whose arrangement makes its own tempo map (Schubert's Ave Maria: a placeholder tempo
    in its MIDI, and ritardandi; tools/music_performance.py schubert_points), as quarter_map's
    steps. That module needs mido, so it is imported only for such a piece."""
    sys.path.insert(0, str(ROOT / 'tools'))
    from music_performance import schubert_points, SCHUBERT_END
    out = []
    for at, beat, q in schubert_points():
        if beat > SCHUBERT_END:
            break
        if not out or abs(q * stretch - out[-1][1]) / out[-1][1] > 0.03:
            out.append((round(at * stretch, 3), round(q * stretch, 4)))
    return out


def pieces():
    """(name, source) for each catalogue piece, in MUSIC_PIECES order (from tools/music_pack.py)."""
    text = (ROOT / 'tools/music_pack.py').read_text()
    block = text[text.index('PIECES = ['):]
    block = block[:block.index('\n]')]
    names = re.findall(r"^ \('([\w-]+)'", block, re.M)
    sources = dict(re.findall(r"'([\w-]+)': '([\w-]+)'", text[text.index('SOURCE = {'):text.index('}', text.index('SOURCE = {'))]))
    return [(n, sources.get(n, n)) for n in names]


def main():
    perf = json.loads((ROOT / 'data/music/performance.json').read_text())
    lines = ['# Generated by tools/music_tempo.py from data/music/source/*.mid and data/music/performance.json;',
             '# edit the tool, then run it again.',
             '# The score\'s quarter note through each piece of MUSIC_PIECES, as played: (from second, the',
             '# quarter\'s length in seconds) pairs. [] where there is no score (the opening call).',
             '', 'MUSIC_TEMPO: vec2[][] = [']
    rows = []
    for name, source in pieces():
        mid = ROOT / 'data/music/source' / f'{source}.mid'
        p = perf.get(name, {})
        if not mid.exists() or 'duration_before' not in p:
            rows.append((f'    []', name))
            continue
        stretch = p['duration_after'] / p['duration_before']
        steps = played_quarter_map(name, stretch) if name == 'schubert-ave-maria' else quarter_map(mid, stretch)
        rows.append(('    [' + ', '.join(f'vec2({a}, {q})' for a, q in steps) + ']', name))
    lines.append('\n'.join(f'{code}{"," if k + 1 < len(rows) else ""}  # {name}' for k, (code, name) in enumerate(rows)))
    lines.append(']')
    out = ROOT / 'src/music_tempo.jo'
    out.write_text('\n'.join(lines) + '\n')
    print(f'wrote {out}: {len(rows)} pieces')


if __name__ == '__main__':
    sys.exit(main())
