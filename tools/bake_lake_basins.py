"""Bake connected terrain depressions, their shore towns, and metric water fields.

Input: untouched relief from lake_contour_survey.jo plus a reviewed sites JSON.
Requires numpy/scipy. No runtime path search or relief dependency in lake_at.
"""
import argparse, json
from pathlib import Path
import numpy as np
from scipy import ndimage


def bake(directory, sites, output):
    surveys = {}
    for line in (directory / 'export.log').read_text().splitlines():
        if not line.startswith('BASIN|'):
            continue
        _, ident, name, tx, ty, tz, radius, x, z, step, n = line.split('|')
        surveys[int(ident)] = dict(name=name, town=[float(tx),float(ty),float(tz)], radius=float(radius), origin=[float(x),float(z)], step=float(step), n=int(n))
    raw=bytearray(); records=[]; bins={}
    for site in sites:
        ident=site['id']; s=surveys[ident]; n=s['n']; step=s['step']; origin=np.array(s['origin'])
        h=np.fromfile(directory/f'{ident}.bin',dtype='<i4').reshape(n,n)/256
        level=site['level']; seed=np.rint((np.array(site['seed'])-origin)/step).astype(int)
        labels,_=ndimage.label(h<level,structure=np.ones((3,3))); label=labels[seed[1],seed[0]]
        assert label>0, f'{s["name"]}: dry basin seed'
        wet=labels==label
        assert not (wet[:4].any() or wet[-4:].any() or wet[:,:4].any() or wet[:,-4:].any()), 'survey must contain the whole basin and spill banks'
        # Other depressions at this altitude are not joined through underground water.
        depth=np.where((labels==0)|wet,level-h,-32.0)
        yy,xx=np.nonzero(wet); x0=max(0,int(xx.min())-8);x1=min(n,int(xx.max())+10);z0=max(0,int(yy.min())-8);z1=min(n,int(yy.max())+10)
        field=np.rint(np.clip(depth[z0:z1,x0:x1],-32,32)*256).astype('<i2')
        field_origin=origin+np.array([x0,z0])*step; offset=len(raw);raw.extend(field.tobytes())
        start=np.array(site['run'][0]);end=np.array(site['run'][1]);axis=(end-start)/np.linalg.norm(end-start);center=(start+end)/2
        assert np.linalg.norm(end-start)>=1440, 'short takeoff run'
        # A shore site is chosen from actual dry relief, with the whole district
        # behind its waterfront. The reviewed seed remains the original identity.
        town=np.array(site['town']); out=np.array(site['out']); old=np.array(s['town'])
        rec=dict(id=ident,name=s['name'],level=level,center=center.tolist(),axis=axis.tolist(),origin=field_origin.tolist(),nx=field.shape[1],nz=field.shape[0],step=step,offset=offset,old=old.tolist(),town=town.tolist(),out=out.tolist(),shore=site['shore'],area=float(wet.sum()*step**2),run=float(np.linalg.norm(end-start)))
        records.append(rec)
        lo=field_origin.copy();hi=lo+np.array([field.shape[1]-1,field.shape[0]-1])*step
        for channel in site.get('channels',[]):
            for node in channel:
                lo=np.minimum(lo,np.array(node[:2])-12);hi=np.maximum(hi,np.array(node[:2])+12)
        rec['bounds']=[*lo,*hi]
        for ix in range(int(np.floor(lo[0]/4096)),int(np.floor(hi[0]/4096))+1):
            for iz in range(int(np.floor(lo[1]/4096)),int(np.floor(hi[1]/4096))+1):bins.setdefault(ix*1024+iz,[]).append(len(records)-1)
    def v2(p):return f'vec2({p[0]:.6f},{p[1]:.6f})'
    def v3(p):return f'vec3({p[0]:.6f},{p[1]:.6f},{p[2]:.6f})'
    source='''# Terrain-filled basins; generated by tools/bake_lake_basins.py.
# Depth samples are signed fixed-point metres at the untouched relief contour.
struct SettlementLake:
    id:int
    name:str
    center:vec2                    # centre of the clear takeoff run
    level:f64
    axis:vec2
    origin:vec2
    nx:int
    nz:int
    step:f64
    offset:int
    old:vec3                       # saved pre-relocation town centre
    town:vec3
    out:vec2
    shore:vec2
    bounds:vec4
SETTLEMENT_LAKES=[
'''
    for r in records:
        source+=f'    SettlementLake({r["id"]},"{r["name"]}",{v2(r["center"])},{r["level"]:.8f},{v2(r["axis"])},{v2(r["origin"])},{r["nx"]},{r["nz"]},{r["step"]},{r["offset"]},{v3(r["old"])},{v3(r["town"])},{v2(r["out"])},{v2(r["shore"])},vec4({v2(r["bounds"][:2])},{v2(r["bounds"][2:])})),\n'
    source+=']\nLAKE_BINS:{int:int[]}={\n'
    for key,value in sorted(bins.items()):source+=f'    {key}:{value},\n'
    source+='''}
const LAKE_CLEAR_RUN=1440.0
const LAKE_CRAFT_MASK=2807
lake_craft_allowed=(craft:int)->bool:craft>=0 and craft<16 and (LAKE_CRAFT_MASK & (1<<craft))!=0
'''
    channels=[];channel_bins={}
    for site in sites:
        for course in site.get('channels',[]):
            for a,b in zip(course,course[1:]):
                index=len(channels);channels.append((site['id'],a,b))
                lo=np.minimum(a[:2],b[:2])-12;hi=np.maximum(a[:2],b[:2])+12
                for ix in range(int(np.floor(lo[0]/256)),int(np.floor(hi[0]/256))+1):
                    for iz in range(int(np.floor(lo[1]/256)),int(np.floor(hi[1]/256))+1):channel_bins.setdefault(ix*8192+iz,[]).append(index)
    channel_source="# Basin inflows and spill channels, surveyed on original relief.\nstruct LakeChannel:\n    id:int\n    a:vec4\n    b:vec4\nLAKE_CHANNELS=[\n"
    for ident,a,b in channels:
        va=','.join(f'{v:.6f}' for v in a);vb=','.join(f'{v:.6f}' for v in b)
        channel_source+=f'    LakeChannel({ident},vec4({va}),vec4({vb})),\n'
    channel_source+=']\nLAKE_CHANNEL_BINS:{int:int[]}={\n'
    for key,value in sorted(channel_bins.items()):channel_source+=f'    {key}:{value},\n'
    channel_source+='}\n'
    (output/'src/lake_channels_data.jo').write_text(channel_source)
    (output/'src/lake_data.jo').write_text(source)
    (output/'assets/lake-basins.bin').write_bytes(raw)
    (directory/'baked-sites.json').write_text(json.dumps(records,indent=2))
    print(f'{len(records)} connected basins; {len(raw)} resident field bytes')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('survey',type=Path);p.add_argument('sites',type=Path);p.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[1]);a=p.parse_args()
    bake(a.survey,json.loads(a.sites.read_text()),a.output)
